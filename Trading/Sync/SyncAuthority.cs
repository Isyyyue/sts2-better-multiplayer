namespace BetterMultiplayer.Trading.Sync;

/// <summary>
/// 本模组在锁步（lockstep）模型下的三种同步策略。
///
/// ★ 为什么需要这个枚举：这三种模式的差异原来只写在各个类的注释里，
///   新人（或下一个 AI）很容易照着 A 场景的写法去改 B 场景，然后踩坑。
///   把它显式写下来，是为了让"这个场景该用哪种模式"变成可检索的规则，
///   而不是靠读散落各处的注释推断。
///
/// 选择的判据只有一条：**这份状态能不能由各端确定性地重算出来？**
///   - 能，且变化是连续动作 → DeterministicLocal（别依赖网络）
///   - 不能（离散改写 / 需要多方库存快照）→ HostArbitrated
///   - 不能，且依赖第三方的状态 → HostValidatedChoice
/// </summary>
internal enum SyncAuthority
{
    /// <summary>
    /// 房主校验后广播唯一事务，各端照抄应用。
    ///
    /// 适用：**离散的状态改写**，且校验需要双方库存快照
    /// （交易——物品转移要同时看两边的牌组、药水槽、遗物、重复检查）。
    /// 两端各自算容易因为快照不一致而分叉，所以由房主一次性裁决。
    ///
    /// 实现：<c>TradeCoordinator</c>（ADR-003）
    /// 配套：修订号 <c>OfferRevision</c> 防乱序、事务号 <c>SessionId</c> 防重复应用
    /// </summary>
    HostArbitrated,

    /// <summary>
    /// 两端各自按确定性算法计算，房主的广播**只作兜底**。
    ///
    /// 适用：**能确定性重算的连续变化**（金币——谁捡到钱这个动作两端都收到，
    /// 算法确定，算出来必然一样）。
    ///
    /// ★ 这里的关键教训：**不要"只让房主算、客户端等广播"**。
    ///   广播是网络，会晚到、会丢；一旦漏掉两端就分叉，游戏会弹"数据不同步"
    ///   并断开连接。曾经就是这么写的，后来改成两端都算（提交 e480ccb）。
    ///
    /// 实现：<c>SharedGoldSync</c>（见其 Postfix 与 ShouldSync 的注释）
    /// </summary>
    DeterministicLocal,

    /// <summary>
    /// 发起者本地做选择，把结果交给房主校验后再广播。
    ///
    /// 适用：**依赖第三方状态的选择**（协助锻造——发起者看不到队友的完整牌组，
    /// 无法本地判定"这张牌现在还能不能升级"）。
    ///
    /// 实现：<c>AssistSmithCoordinator</c>（ADR-004）
    /// 失败处理：校验不过就整体取消，且**不消耗发起者的篝火行动**
    /// </summary>
    HostValidatedChoice,
}
